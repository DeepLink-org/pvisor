#!/usr/bin/env python3
"""Bounded real KVM scaling probes: at most four guests, one per capped Worker.

Benchmark: B-CLUSTER (benchmark/README.md#b-cluster), role user-facing.
Motivation: users scaling Agents need to know whether more Workers and
resources yield proportionally more valid results.
Conclusion sought: completed, verified tasks per second against Worker count
under a fixed per-Worker budget, plus control-plane memory and restart cost
at N retained records. Ready time alone is not throughput.
Design: per-Worker resource caps, Worker count sweep, verified completion as
the output metric; control-plane history size swept separately.

Uses the quickstart's pinned binaries, minimal rootfs and service isolation.
No high-density sweep or model traffic is generated by this runner.
"""

import argparse
import copy
import hashlib
import importlib.util
import json
import os
import platform
import re
import shutil
import signal
import statistics
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MIB = 1024**2
spec = importlib.util.spec_from_file_location("quickstart", ROOT / "scripts/cluster-quickstart.py")
qs = importlib.util.module_from_spec(spec)
spec.loader.exec_module(qs)


def digest(path):
    with path.open("rb") as source:
        return hashlib.file_digest(source, "sha256").hexdigest()


def counters(group, name):
    return {
        k: int(v) for k, v in (line.split() for line in (group / name).read_text().splitlines())
    }


def snapshot(groups):
    result = {}
    for role, group in groups.items():
        stat = counters(group, "memory.stat")
        result[role] = {
            "current_bytes": int((group / "memory.current").read_text()),
            "anon_bytes": stat["anon"],
            "file_bytes": stat["file"],
            "cpu": counters(group, "cpu.stat"),
            "events": counters(group, "memory.events"),
        }
        assert result[role]["events"]["oom"] == result[role]["events"]["oom_kill"] == 0
    return result


def native_identities(group):
    """Verify actual KVM processes, not just Controller Running receipts."""
    result = []
    for file in [group / "cgroup.procs", *group.rglob("cgroup.procs")]:
        for pid in set(file.read_text().split()):
            proc = Path("/proc") / pid
            try:
                kvm = any("kvm-vm" in os.readlink(fd) for fd in (proc / "fd").iterdir())
                if not kvm:
                    continue
                stat = (proc / "stat").read_text().rsplit(")", 1)[1].split()
                values = {}
                for line in (proc / "smaps_rollup").read_text().splitlines():
                    if line.startswith(("Rss:", "Pss:")):
                        values[line.split(":")[0].lower() + "_bytes"] = int(line.split()[1]) * 1024
                result.append({"pid": int(pid), "start_time_ticks": int(stat[19]), **values})
            except (FileNotFoundError, ProcessLookupError):
                continue
    return list({row["pid"]: row for row in result}.values())


def batch(session, groups, size, repetition, warmup, report):
    row = {
        "sandboxes": size,
        "repetition": repetition,
        "warmup": warmup,
        "passed": False,
        "baseline": snapshot(groups),
        "tasks": [],
        "plateau": [],
    }
    report["batches"].append(row)  # Retain failures; never discard them from the report.
    started = time.monotonic()
    base = json.loads((session.state / "inputs/hello.json").read_text())
    for node in "abcd"[:size]:
        task = copy.deepcopy(base)
        id = f"scale-{size}-{repetition}-{node}"
        task["id"] = task["run"]["run_id"] = id
        task["labels"]["quickstart-node"] = node
        # A real guest filesystem marker measures readiness. Keep every guest
        # alive for six seconds to observe a simultaneous memory plateau.
        task["run"]["invocation"]["args"] = [
            "-c",
            "printf ready > /tmp/scale-ready; /bin/sleep 6; printf 'scale-ok\\n'",
        ]
        task["retain_artifacts"] = {"version": 1, "trace": True, "workspace_upper": False}
        path = session.state / f"inputs/{id}.json"
        qs.write_json(path, task)
        begun = time.monotonic()
        session.ctl("submit", str(path))
        row["tasks"].append(
            {
                "id": id,
                "node": node,
                "submit_offset_ms": (begun - started) * 1000,
                "accept_ms": (time.monotonic() - begun) * 1000,
            }
        )
    deadline = started + 45
    while not all("ready_ms" in task for task in row["tasks"]):
        for task in row["tasks"]:
            marker = (
                session.state / f"worker-{task['node']}/tasks/{task['id']}-1/upper/tmp/scale-ready"
            )
            if "ready_ms" not in task and marker.is_file():
                task["ready_ms"] = (time.monotonic() - started) * 1000 - task["submit_offset_ms"]
        if time.monotonic() > deadline:
            raise TimeoutError(f"guest readiness timed out: {row['tasks']}")
        time.sleep(0.02)
    row["all_ready_ms"] = (time.monotonic() - started) * 1000
    row["launches_per_second"] = size / (row["all_ready_ms"] / 1000)
    row["native_identities"] = {
        role: native_identities(group) for role, group in groups.items() if role != "controller"
    }
    assert all(len(pids) == 1 for pids in row["native_identities"].values()), row
    for _ in range(10):
        row["plateau"].append(snapshot(groups))
        time.sleep(0.05)
    for task in row["tasks"]:
        record = session.wait(task["id"])
        assert record["phase"] == "succeeded", record
        assert record["result"]["output"]["stdout"] == "scale-ok\n", record
        assert record["lease"]["key"]["worker_id"] == f"qs-{task['node']}"
        task["completion_observed_ms"] = (time.monotonic() - started) * 1000
    row["after"] = snapshot(groups)
    row["passed"] = True
    memory = statistics.median(sum(v["current_bytes"] for v in s.values()) for s in row["plateau"])
    print(
        f"PASS n={size} repetition={repetition} warmup={warmup} "
        f"ready={row['all_ready_ms']:.1f}ms cgroup={memory / MIB:.1f}MiB",
        flush=True,
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--state", type=Path, required=True, help="new private directory outside checkout"
    )
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--firmware-dir", type=Path, required=True)
    parser.add_argument("--bin-dir", type=Path, default=ROOT / "target/debug")
    parser.add_argument("--sizes", type=int, nargs="+", default=[1, 2, 4])
    parser.add_argument("--repetitions", type=int, default=5)
    args = parser.parse_args()
    if (
        not args.sizes
        or any(n not in (1, 2, 4) for n in args.sizes)
        or len(set(args.sizes)) != len(args.sizes)
    ):
        parser.error("sizes must be unique values from 1, 2, 4")
    if not 1 <= args.repetitions <= 10:
        parser.error("repetitions must be 1..10")
    state = args.state.resolve()
    if state.is_relative_to(ROOT) or state.exists():
        parser.error("state must be a new directory outside the checkout")
    available = (
        int(re.search(r"MemAvailable:\s+(\d+)", Path("/proc/meminfo").read_text())[1]) * 1024
    )
    if available < 3 * 1024**3:
        raise RuntimeError("need at least 3 GiB MemAvailable; no services started")
    for device in ["/dev/kvm", "/dev/fuse"]:
        if not os.access(device, os.R_OK | os.W_OK):
            raise RuntimeError(f"need read/write access to {device}")
    if qs.execute(["systemctl", "--user", "is-system-running"]).strip() != "running":
        raise RuntimeError("running Linux user systemd manager required")
    state.mkdir(mode=0o700)
    # Pin once across all sizes: another build must not change the executable.
    pinned = state / "pinned"
    pinned.mkdir()
    for name in ["pvisor-cluster", "pvisor-worker"]:
        shutil.copy2(args.bin_dir / name, pinned / name)
    report = {
        "schema": "pvisor-cluster-scalability/v1",
        "passed": False,
        "started_at_unix_ms": int(time.time() * 1000),
        "command": ["python3", "benchmark/pvisor/cluster_scalability.py", *os.sys.argv[1:]],
        "environment": {
            "kernel": platform.platform(),
            "cpu": next(
                line.split(":", 1)[1].strip()
                for line in Path("/proc/cpuinfo").read_text().splitlines()
                if line.startswith("model name")
            ),
            "meminfo_before": Path("/proc/meminfo").read_text(),
        },
        "provenance": {
            "revision": qs.execute(["git", "rev-parse", "HEAD"]).strip(),
            "dirty": qs.execute(["git", "status", "--short"]),
            "binary_sha256": {p.name: digest(p) for p in pinned.iterdir()},
            "runner_sha256": digest(Path(__file__)),
            "quickstart_sha256": digest(ROOT / "scripts/cluster-quickstart.py"),
            "firmware_sha256": digest(args.firmware_dir / "libkrunfw.so.5"),
        },
        "conditions": {
            "sizes": args.sizes,
            "repetitions": args.repetitions,
            "warmup_batches_per_size": 1,
            "max_simultaneous_guests": max(args.sizes),
            "guest_ram_bytes": 128 * MIB,
            "guest_vcpus": 1,
            "worker_per_guest": True,
            "worker_memory_max_bytes": 512 * MIB,
            "worker_cpu_cores": 0.5,
            "controller_memory_max_bytes": 256 * MIB,
            "controller_cpu_cores": 0.25,
            "swap_max_bytes": 0,
            "task_cpu_time_ms": 2000,
            "task_timeout_ms": 60000,
            "worker_poll_ms": 200,
            "ready_poll_ms": 20,
            "plateau_samples": 10,
            "plateau_sample_interval_ms": 50,
            "guest_hold_seconds": 6,
            "startup_definition": "task submit start through guest-created ready marker; includes CLI, HTTP, intent persistence, scheduling and VM start; excludes service/rootfs setup",
            "memory_definition": "sum of disjoint Controller/Worker cgroup memory.current at simultaneous guest-ready plateau, includes charged file cache; anon/file reported separately; native process PSS also sampled",
            "cache": "prepared minimal rootfs; one warmup excluded per size; host caches not flushed",
            "scope": "single shared Linux host; real native KVM shell probes; no model/Gateway traffic or multi-host claim",
            "launch_rate_note": "N/time-to-all-ready; not useful-work throughput; six-second hold excluded",
        },
        "groups": [],
        "batches": [],
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    session = None
    roles = []

    def interrupted(signum, frame):
        raise KeyboardInterrupt(f"signal {signum}")

    signal.signal(signal.SIGTERM, interrupted)
    try:
        for size in args.sizes:
            qs.prepare(state / f"n{size}", "vm", pinned, args.firmware_dir)
            session = qs.Session(state / f"n{size}")
            qs.write_json(
                session.state / "quotas.json",
                {
                    "quickstart": {
                        "slots": size,
                        "memory_bytes": size * 128 * MIB,
                        "cpu_millis": size * 500,
                    }
                },
            )
            roles = ["controller", *[f"worker-{node}" for node in "abcd"[:size]]]
            groups = {}
            try:
                for role in roles:
                    session.launch(role)
                    if role == "controller":
                        session.until(lambda: session.api("/health"), timeout=15)
                session.until(lambda: len(session.ctl("workers")) == size, timeout=20)
                group_record = {"sandboxes": size, "cgroups": {}}
                report["groups"].append(group_record)
                for role in roles:
                    raw = qs.execute(
                        [
                            "systemctl",
                            "--user",
                            "show",
                            session.unit(role),
                            "-p",
                            "ControlGroup",
                            "--value",
                        ]
                    ).strip()
                    group = Path("/sys/fs/cgroup") / raw.lstrip("/")
                    maximum = int((group / "memory.max").read_text())
                    quota, period = map(int, (group / "cpu.max").read_text().split())
                    assert maximum == (256 if role == "controller" else 512) * MIB
                    assert quota / period == (0.25 if role == "controller" else 0.5)
                    assert (group / "memory.swap.max").read_text().strip() == "0"
                    groups[role] = group
                    group_record["cgroups"][role] = {
                        "memory_max": maximum,
                        "cpu_max": [quota, period],
                        "swap_max": 0,
                    }
                for rep in range(args.repetitions + 1):
                    batch(session, groups, size, rep, rep == 0, report)
                    qs.write_json(args.output, report)
                group_record["final"] = snapshot(groups)
            finally:
                for role in reversed(roles):
                    session.stop(role)
                roles = []
                session = None
        report["passed"] = True
    except BaseException as error:
        report["error"] = f"{type(error).__name__}: {error}"
        raise
    finally:
        if session:
            for role in reversed(roles):
                session.stop(role)
        report["finished_at_unix_ms"] = int(time.time() * 1000)
        qs.write_json(args.output, report)


if __name__ == "__main__":
    main()
